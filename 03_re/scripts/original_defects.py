"""original_defects.py - write ORIGINAL_DEFECTS.md, the log of defects / bugs / glitches found in the ORIGINAL game.

The source of truth is 03_re/ledger/known_gaps.csv (rows of kind 'original-defect'); this file only renders them, so
the log can never disagree with the ledger. Run by roadmap_sync.py on every step. To log a new defect, add a KG row
of kind original-defect (never edit ORIGINAL_DEFECTS.md by hand).
"""
import csv, datetime, io, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))


def main():
    rows = [r for r in csv.DictReader(io.open(os.path.join(ROOT, '03_re', 'ledger', 'known_gaps.csv'), encoding='utf-8'))
            if r['kind'] == 'original-defect']
    out = ['# Defects found in the original Recoil (1999)', '',
           'Generated by `03_re/scripts/original_defects.py` from `03_re/ledger/known_gaps.csv` (kind `original-defect`) - '
           'do not edit by hand. Updated %s. %d defects.' % (datetime.date.today(), len(rows)), '',
           'Each is a bug in the shipped Recoil.exe found while porting and testing it against the original. The remake '
           'reproduces every one 1:1 unless its entry says a deviation was decided.', '',
           '| ID | Subsystem | Status | Defect | Decision / how to close | Found by |', '|---|---|---|---|---|---|']
    for r in rows:
        cell = lambda s: s.replace('|', '\\|').replace('\n', ' ')
        out.append('| %s | %s | %s | %s | %s | %s |' % (r['id'], r['subsystem'], r['status'], cell(r['description']),
                                                      cell(r['how_to_close']), cell(r['source'])))
    io.open(os.path.join(ROOT, 'ORIGINAL_DEFECTS.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print('ORIGINAL_DEFECTS.md: %d defects' % len(rows))


if __name__ == '__main__':
    main()
