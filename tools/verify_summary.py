"""verify_summary.py - classify the FAIL / NOT-RUN rows of 03_re/staging/verify/verify_results.csv by failure shape (no tokens).

Written 2026-09-29 from the hand triage in 03_re/staging/verify/for_opus.md. It never edits the ledger or any test; it writes
03_re/staging/verify/verify_summary.md and prints the counts. The shapes are HYPOTHESES about the cause, not verdicts:
  original-AV        "outcome 3221225477 vs 0": the ORIGINAL faulted (0xC0000005) and the port returned. Split by whether the
                     function's listing references a non-msvcrt / non-MFC import slot directly (direct = matches the "unbound
                     imports in the mapped original" explanation; callees are not followed).
  heap-corruption    0xc0000374 (arena words used as sizes / pointers)
  shard-died         "test failed" with no per-function line
  eax-only           first difference is EAX (a leftover or a heap pointer in a function nobody reads EAX from is a test artifact,
                     but that needs the call sites read: see for_opus.md)
  memory-diff        first difference is a block / arena word / heap call sequence
  other              anything else
usage: python tools/verify_summary.py
"""
import collections, csv, glob, os, re

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
os.chdir(ROOT)


def slot_dlls():
    m = {}
    for f in glob.glob('05_remake/src/platform/iat_*.h') + ['05_remake/src/platform/advapi.h', '05_remake/src/platform/mfc42.h']:
        if os.path.exists(f):
            dll = os.path.basename(f).replace('iat_', '').replace('.h', '')
            for a in re.findall(r'g_Iat_\w*?_([0-9a-f]{8})\b', open(f, encoding='utf-8').read()):
                m[int(a, 16)] = dll
    return m


def bodies():
    b = {}
    for lp in glob.glob('03_re/listings/unported/*.txt') + glob.glob('03_re/listings/*.txt'):
        for chunk in open(lp, encoding='utf-8').read().split('### ')[1:]:
            b.setdefault('0x' + chunk.split()[0], chunk)
    return b


def main():
    rows = list(csv.DictReader(open('03_re/staging/verify/verify_results.csv', encoding='utf-8')))
    sd, bd = slot_dlls(), bodies()
    counts = collections.Counter(r['result'] for r in rows)
    groups = collections.defaultdict(list)
    for r in rows:
        if r['result'] == 'PASS':
            continue
        d = r['detail']
        if r['result'] == 'NOT-RUN':
            groups['not-run (no result for its test)'].append(r)
            continue
        if 'outcome 3221225477 vs 0' in d:
            body = bd.get(r['address'], '')
            dlls = {sd.get(int(m, 16)) for m in re.findall(r'\[0x(004c[c-f][0-9a-f]{3})\]', body)} - {None, 'msvcrt', 'mfc42'}
            groups['original-AV, direct non-msvcrt import' if dlls else 'original-AV, no direct import (callee?)'].append(r)
        elif '0xc0000374' in d:
            groups['heap-corruption'].append(r)
        elif d.startswith('test failed') or 'ESCAPED FAULT' in d or 'crashed' in d:
            groups['shard-died / escaped fault'].append(r)
        elif re.search(r'DIFF #\d+: EAX', d):
            groups['eax-only first difference'].append(r)
        elif re.search(r'block|arena word|heap call', d):
            groups['memory-diff'].append(r)
        else:
            groups['other'].append(r)
    out = ['# verify_summary (generated by tools/verify_summary.py)', '',
           'results: ' + ', '.join('%s %d' % kv for kv in sorted(counts.items())), '']
    for k in sorted(groups):
        out.append('## %s (%d)' % (k, len(groups[k])))
        for r in groups[k]:
            out.append('- %s %s [%s] %s' % (r['address'], r['name'], r['test'].replace('native_fuzz_', '').replace('_match_original', ''),
                                            r['detail'][:90]))
        out.append('')
    open('03_re/staging/verify/verify_summary.md', 'w', encoding='utf-8').write('\n'.join(out))
    print('results:', dict(counts))
    for k in sorted(groups):
        print('  %-44s %d' % (k, len(groups[k])))


if __name__ == '__main__':
    main()
