"""embed_quality_example.py - 05_remake/setup/quality_example.png (the tank-track comparison Setup shows beside the
texture choice: original | Real-ESRGAN | asset pack, a 16x16 detail, user 2026-10-20) -> quality_example.h, so the
source tree holds no image file. usage: python tools/embed_quality_example.py"""
import os
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
src = os.path.join(ROOT, '05_remake', 'setup', 'quality_example.png')
d = open(src, 'rb').read()
lines = [', '.join('0x%02x' % b for b in d[i:i + 24]) for i in range(0, len(d), 24)]
with open(os.path.join(ROOT, '05_remake', 'setup', 'quality_example.h'), 'w', newline='\n') as f:
    f.write('// quality_example.h - generated by tools/embed_quality_example.py from quality_example.png (not in git): the\n'
            '// texture quality example Setup shows (one detail of the tank track: original, Real-ESRGAN, asset pack).\n'
            '#pragma once\nstatic const unsigned char kQualityExamplePng[] = {\n    ' + ',\n    '.join(lines) + '\n};\n')
print('%d bytes embedded' % len(d))
