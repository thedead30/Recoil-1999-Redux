"""gen_iat_slots.py - generate the port's import-slot variables for every import of Recoil.exe from one DLL.

Writes 05_remake/src/platform/iat_<dll>.h/.cpp: one `void* g_Iat_<name>_<slot>` per import, bound with
GetProcAddress to the system DLL (decision D5: the remake calls the same DLL functions the reference captures ran
against). Data imports (_iob, _pctype, __mb_cur_max, _HUGE, ...) resolve to the variable's address, exactly what
the original's slot holds.
usage: python tools/asm_port/gen_iat_slots.py [DLL] [--out DIR]      (default msvcrt.dll; e.g. kernel32.dll)
Imports by ordinal (MFC42.DLL) become g_Iat_<STEM>_<ordinal>_<slot>, bound with GetProcAddress by ordinal; slots that
platform code already defines by hand (MFC42 #823 operator new, #825 operator delete: platform/mfc42.cpp) are skipped.
--out DIR writes there instead of 05_remake/src/platform (to look at the result first).
"""
import io, os, struct, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
EXE = os.path.join(ROOT, '00_original', 'game_install', 'Recoil.exe')


HAND_DEFINED = {0x004cc2ac, 0x004cc2b8}  # MFC42 #823 / #825: platform/mfc42.cpp binds them to the platform allocator


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    outdir = sys.argv[sys.argv.index('--out') + 1] if '--out' in sys.argv else None
    if outdir:
        args = [a for a in args if a != outdir]
    want = (args[0] if args else 'msvcrt.dll').lower()
    stem = want[:-4] if want.endswith('.dll') else want
    b = open(EXE, 'rb').read()
    pe = struct.unpack_from('<I', b, 0x3c)[0]
    nsec = struct.unpack_from('<H', b, pe + 6)[0]
    opt = struct.unpack_from('<H', b, pe + 20)[0]
    secs = [struct.unpack_from('<IIII', b, pe + 24 + opt + i * 40 + 8) for i in range(nsec)]

    def off(rva):
        for vs, v, rs, ro in secs:
            if v <= rva < v + rs:
                return rva - v + ro

    slots = []
    d = off(struct.unpack_from('<I', b, pe + 24 + 104)[0])
    while True:
        oft, ts, fc, name, ft = struct.unpack_from('<IIIII', b, d)
        if not name:
            break
        dll = b[off(name):b.index(b'\0', off(name))].decode()
        if dll.lower() == want:
            dll_name = dll
            t = off(oft or ft)
            k = 0
            while True:
                v = struct.unpack_from('<I', b, t + 4 * k)[0]
                if not v:
                    break
                if v & 0x80000000:  # by ordinal (MFC42.DLL)
                    if (0x400000 + ft + 4 * k) not in HAND_DEFINED:
                        slots.append((0x400000 + ft + 4 * k, '%s_%d' % (stem.upper(), v & 0xffff), v & 0xffff))
                else:
                    o = off(v) + 2
                    slots.append((0x400000 + ft + 4 * k, b[o:b.index(b'\0', o)].decode(), None))
                k += 1
        d += 20
    ident = lambda n: n.replace('?', '_').replace('@', '_')
    h = ['// SUBSYSTEM: platform',
         '// Import slots for every %s import of Recoil.exe (import table), bound to the system %s.' % (dll_name, want),
         '// Generated by tools/asm_port/gen_iat_slots.py - do not edit by hand. PLATFORM.',
         '#pragma once', '', 'namespace recoil {', '']
    c = ['// SUBSYSTEM: platform', '// Generated by tools/asm_port/gen_iat_slots.py - do not edit by hand. PLATFORM.',
         '#include "platform/iat_%s.h"' % stem, '', '#define WIN32_LEAN_AND_MEAN', '#include <windows.h>', '', 'namespace recoil {',
         'namespace {', 'void* crt(const char* name) { return reinterpret_cast<void*>(GetProcAddress(LoadLibraryA("%s"), name)); }' % want,
         ] + (['void* ord(unsigned n) { return reinterpret_cast<void*>(GetProcAddress(LoadLibraryA("%s"), MAKEINTRESOURCEA(n))); }' % want]
              if any(o is not None for _, _, o in slots) else []) + [
         '}  // namespace', '']
    for va, n, o in slots:
        h.append('extern void* g_Iat_%s_%08x;  // %s' % (ident(n), va, n if o is None else 'ordinal %d' % o))
        c.append('void* g_Iat_%s_%08x = %s;' % (ident(n), va, 'crt("%s")' % n if o is None else 'ord(%d)' % o))
    h += ['', '}  // namespace recoil', '']
    c += ['', '}  // namespace recoil', '']
    out = outdir or os.path.join(ROOT, '05_remake', 'src', 'platform')
    os.makedirs(out, exist_ok=True)
    io.open(os.path.join(out, 'iat_%s.h' % stem), 'w', encoding='utf-8', newline='').write('\n'.join(h))
    io.open(os.path.join(out, 'iat_%s.cpp' % stem), 'w', encoding='utf-8', newline='').write('\n'.join(c))
    print(len(slots), stem, 'slots')


if __name__ == '__main__':
    main()
